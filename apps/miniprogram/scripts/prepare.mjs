// Prepares files the WeChat DevTools project needs but cannot resolve from a pnpm workspace:
// the TDesign component build, the shared package bundle, and the theme.
// lib/theme.wxss holds TDesign's tokens, the brand tokens and styles/tokens.wxss. Each keeps its
// prefers-color-scheme blocks on `page`, which follow the system, and is also copied into
// .theme-light and .theme-dark for the in-app setting (see components/theme-root).
// lib/native-theme.js carries theme.json for the native bars the setting has to set itself.
// API_BASE_URL (default http://localhost:8787) is written to lib/env.js for the app to read.
// The gitignored project.private.config.json carries WX_APPID when set, so a different AppID
// (such as a sandbox test AppID) works without editing project.config.json, and turns off the
// domain check when the API is plain http, which only a local development server is.
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const require = createRequire(import.meta.url)
const appDir = fileURLToPath(new URL('../miniprogram/', import.meta.url))
const libDir = join(appDir, 'lib')
const npmDir = join(appDir, 'miniprogram_npm')

rmSync(npmDir, { recursive: true, force: true })
rmSync(libDir, { recursive: true, force: true })
mkdirSync(libDir, { recursive: true })

const tdesignDist = join(
  dirname(require.resolve('tdesign-miniprogram/package.json')),
  'miniprogram_dist',
)
cpSync(tdesignDist, join(npmDir, 'tdesign-miniprogram'), { recursive: true })

// Reads top-level `page { }` rules and `@media (prefers-color-scheme) { page { } }` blocks and
// returns the custom properties each mode gets, in source order so later ones still win.
function themeDeclarations(css, source) {
  const out = { light: [], dark: [] }
  const text = css.replace(/\/\*[\s\S]*?\*\//g, '')
  // Splits a run of rules into [prelude, body] pairs, matching braces one level deep.
  const blocks = (src) => {
    const list = []
    let at = 0
    while (at < src.length) {
      const open = src.indexOf('{', at)
      if (open === -1) {
        if (src.slice(at).trim()) throw new Error(`${source}: stray text "${src.slice(at).trim()}"`)
        break
      }
      let depth = 1
      let close = open + 1
      for (; close < src.length && depth > 0; close++) {
        if (src[close] === '{') depth++
        else if (src[close] === '}') depth--
      }
      if (depth > 0) throw new Error(`${source}: unbalanced braces`)
      list.push([src.slice(at, open).trim(), src.slice(open + 1, close - 1)])
      at = close
    }
    return list
  }
  const take = (selector, body, modes) => {
    const parts = selector.split(',').map((p) => p.trim())
    if (!parts.every((p) => p === 'page' || p === '.page')) {
      throw new Error(`${source}: theme files may only style page, found "${selector}"`)
    }
    for (const decl of body.split(';')) {
      const d = decl.trim()
      if (d.startsWith('--')) for (const mode of modes) out[mode].push(d)
    }
  }
  for (const [prelude, body] of blocks(text)) {
    if (prelude.startsWith('@media')) {
      const mode = prelude.match(
        /^@media\s*\(\s*prefers-color-scheme\s*:\s*(light|dark)\s*\)$/,
      )?.[1]
      if (!mode) throw new Error(`${source}: unexpected "${prelude}"`)
      for (const [selector, inner] of blocks(body)) take(selector, inner, [mode])
    } else {
      take(prelude, body, ['light', 'dark'])
    }
  }
  return out
}

const themeSources = [
  [
    'tdesign',
    readFileSync(join(npmDir, 'tdesign-miniprogram/common/style/theme/_index.wxss'), 'utf8'),
  ],
  ['brand', readFileSync(require.resolve('@rs/theme/brand.wxss'), 'utf8')],
  ['tokens', readFileSync(join(appDir, 'styles/tokens.wxss'), 'utf8')],
]
const forced = { light: [], dark: [] }
for (const [name, css] of themeSources) {
  const decls = themeDeclarations(css, name)
  forced.light.push(...decls.light)
  forced.dark.push(...decls.dark)
}
// A token only one mode sets would leak from the system theme on page into the forced other
// mode, so the forced block unsets it, which is what the system theme sees.
const names = (decls) => new Set(decls.map((d) => d.slice(0, d.indexOf(':')).trim()))
const declared = { light: names(forced.light), dark: names(forced.dark) }
for (const [mode, other] of [
  ['light', 'dark'],
  ['dark', 'light'],
]) {
  const unset = [...declared[other]].filter((name) => !declared[mode].has(name))
  forced[mode].unshift(...unset.map((name) => `${name}:initial`))
}
writeFileSync(
  join(libDir, 'theme.wxss'),
  [
    '/* Generated by scripts/prepare.mjs. Do not edit; change styles/tokens.wxss instead. */',
    ...themeSources.map(([, css]) => css.trim()),
    ...['light', 'dark'].map((mode) => `.theme-${mode}{${forced[mode].join(';')}}`),
    '',
  ].join('\n'),
)

const themeJson = JSON.parse(readFileSync(join(appDir, 'theme.json'), 'utf8'))
const tabs = JSON.parse(readFileSync(join(appDir, 'app.json'), 'utf8')).tabBar.list.map((tab) => ({
  pagePath: tab.pagePath,
  iconPath: tab.iconPath,
  selectedIconPath: tab.selectedIconPath,
}))
writeFileSync(
  join(libDir, 'native-theme.js'),
  `module.exports = ${JSON.stringify({ ...themeJson, tabs }, null, 2)}\n`,
)
writeFileSync(
  join(libDir, 'native-theme.d.ts'),
  [
    "type Values = Record<'navBgColor' | 'navTextStyle' | 'bgColor' | 'bgTextStyle' | 'tabColor' |",
    "  'tabSelectedColor' | 'tabBgColor' | 'tabBorderStyle', string> & Record<string, string>",
    'export declare const light: Values',
    'export declare const dark: Values',
    '/** app.json tabBar.list; icon paths are theme.json variables such as "@bookingIcon". */',
    'export declare const tabs: { pagePath: string; iconPath: string; selectedIconPath: string }[]',
    '',
  ].join('\n'),
)

const sharedEntry = require.resolve('@rs/shared/client')
await build({
  entryPoints: [sharedEntry],
  outfile: join(libDir, 'shared.js'),
  bundle: true,
  format: 'cjs',
  platform: 'neutral',
  target: 'es2017',
  logLevel: 'warning',
})
const typesPath = relative(libDir, sharedEntry).replace(/\\/g, '/').replace(/\.ts$/, '')
writeFileSync(join(libDir, 'shared.d.ts'), `export * from '${typesPath}'\n`)

const apiBaseUrl = (process.env.API_BASE_URL?.trim() || 'http://localhost:8787').replace(/\/+$/, '')
writeFileSync(
  join(libDir, 'env.js'),
  `module.exports = { apiBaseUrl: ${JSON.stringify(apiBaseUrl)} }\n`,
)
writeFileSync(join(libDir, 'env.d.ts'), 'export declare const apiBaseUrl: string\n')

// DevTools keeps its own local settings in the same file, so merge into it.
const privateConfigPath = fileURLToPath(new URL('../project.private.config.json', import.meta.url))
const privateConfig = existsSync(privateConfigPath)
  ? JSON.parse(readFileSync(privateConfigPath, 'utf8'))
  : {}
const appid = process.env.WX_APPID?.trim()
if (appid) privateConfig.appid = appid
// Only a plain-http local API needs the domain check off; an https one should be checked.
privateConfig.setting = { ...privateConfig.setting, urlCheck: !apiBaseUrl.startsWith('http://') }
writeFileSync(privateConfigPath, `${JSON.stringify(privateConfig, null, 2)}\n`)
