// Writes brand.css (web) and brand.wxss (mini program) from tokens.json.
// Only the 10-step brand scale is overridden; TDesign derives hover, active and the rest from it.
// Run with --check to fail when the committed files are out of date.
import { readFileSync, writeFileSync } from 'node:fs'

const dir = new URL('.', import.meta.url)
const tokens = JSON.parse(readFileSync(new URL('tokens.json', dir), 'utf8'))

const block = (selector, mode) =>
  [
    `${selector} {`,
    ...tokens.brand[mode].map((hex, i) => `  --td-brand-color-${i + 1}: ${hex};`),
    `  --rs-hint-color: ${tokens.hint[mode]};`,
    '}',
  ].join('\n')

const header = '/* Generated by generate.mjs from tokens.json. Do not edit. */'

const css = [
  header,
  block(":root,\n:root[theme-mode='light']", 'light'),
  block(":root.dark,\n:root[theme-mode='dark']", 'dark'),
  '',
].join('\n')

const wxss = [
  header,
  block('page', 'light'),
  `@media (prefers-color-scheme: dark) {\n${block('page', 'dark').replace(/^/gm, '  ')}\n}`,
  '',
].join('\n')

const outputs = { 'brand.css': css, 'brand.wxss': wxss }
const check = process.argv.includes('--check')
let stale = false
for (const [name, content] of Object.entries(outputs)) {
  const url = new URL(name, dir)
  if (check) {
    let current = ''
    try {
      current = readFileSync(url, 'utf8')
    } catch {}
    if (current !== content) {
      console.error(`${name} is out of date. Run: pnpm --filter @rs/theme generate`)
      stale = true
    }
  } else {
    writeFileSync(url, content)
  }
}
if (stale) process.exit(1)
